# Вариант 1: без генератора списка
print("=== Вариант 1 (без генератора списка) ===")

a = []
for i in range(10):
    num = int(input(f"Введите число {i+1}: "))
    a.append(num)

# Создаем второй массив для отрицательных чисел
b = []
for num in a:
    if num < 0:
        b.append(num)

print(f"\nИсходный массив: {a}")
print(f"Отрицательные числа: {b}")

