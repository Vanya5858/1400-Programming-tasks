# Вариант 1: без генератора списка
print("=== Вариант 1 (без генератора списка) ===")

n = int(input("Введите размер массива: "))
arr = []
for i in range(n):
    num = int(input(f"Введите элемент {i+1}: "))
    arr.append(num)

# Создаем новый массив без чисел 13
new_arr = []
count_13 = 0
for num in arr:
    if num == 13:
        count_13 += 1
    else:
        new_arr.append(num)

print(f"\nИсходный массив: {arr}")
print(f"Новый массив (без чисел 13): {new_arr}")
print(f"Найдено чисел 13: {count_13}")

# Вариант 2: с генератором списка
print("\n=== Вариант 2 (с генератором списка) ===")

# Используем те же данные или можно ввести новые
arr2 = arr.copy()  # используем те же данные для сравнения

# Используем генератор списка
new_arr2 = [num for num in arr2 if num != 13]
count_13_2 = arr2.count(13)

print(f"\nИсходный массив: {arr2}")
print(f"Новый массив (без чисел 13): {new_arr2}")
print(f"Найдено чисел 13: {count_13_2}")

# Дополнительная информация
print(f"\nРазмер исходного массива: {len(arr)}")
print(f"Размер нового массива: {len(new_arr)}")
print(f"Процент чисел 13: {count_13/len(arr)*100:.1f}%" if len(arr) > 0 else "Массив пуст")

# Проверка правильности обоих методов
if new_arr == new_arr2:
    print("\n✓ Оба метода дали одинаковый результат")
else:
    print("\n✗ Результаты методов различаются")
