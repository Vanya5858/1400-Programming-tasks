#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "RU");
    cout << "Поиск трехзначных чисел, удовлетворяющих условиям:" << endl;
    cout << "i % 47 == 43 и i % 43 == 45" << endl << endl;

    bool found = false;

    // Проверим математически: если i % 47 = 43, то i = 47k + 43
    // Если i % 43 = 45, то i = 43m + 45
    // Значит 47k + 43 = 43m + 45
    // 47k - 43m = 2

    cout << "Математический анализ:" << endl;
    cout << "47k + 43 = 43m + 45" << endl;
    cout << "47k - 43m = 2" << endl << endl;

    cout << "Перебор возможных значений:" << endl;
    for (int k = 0; k <= 21; k++) { // 47*21 + 43 = 1030 (уже четырехзначное)
        int i = 47 * k + 43;
        if (i >= 100 && i <= 999) {
            cout << "k=" << k << ", i=" << i << ", i%47=" << i % 47 << ", i%43=" << i % 43;
            if (i % 43 == 45) {
                cout << " <- НАЙДЕНО!" << endl;
                found = true;
            }
            else {
                cout << endl;
            }
        }
    }

    if (!found) {
        cout << "\nТаких трехзначных чисел не существует!" << endl;
        cout << "Причина: уравнение 47k - 43m = 2 не имеет решений в трехзначном диапазоне" << endl;
        cout << "с условиями i % 47 = 43 и i % 43 = 45 одновременно" << endl;
    }

    return 0;
}