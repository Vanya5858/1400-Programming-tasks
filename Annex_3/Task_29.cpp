#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "RU");

    int X, Y, Z;

    cout << "Примеры условий:" << endl;

    // a)
    X = 3; Y = 7;
    cout << "a) Каждое из чисел X и Y нечетное: " << (X % 2 != 0 && Y % 2 != 0)
        << " (X=" << X << ", Y=" << Y << ")" << endl;

    // б)
    X = 15; Y = 25;
    bool только_одно_меньше_20 = (X < 20 && Y >= 20) || (X >= 20 && Y < 20);
    cout << "б) Только одно из чисел X и Y меньше 20: " << только_одно_меньше_20
        << " (X=" << X << ", Y=" << Y << ")" << endl;

    // в)
    X = 0; Y = 5;
    cout << "в) Хотя бы одно из чисел X и Y равно нулю: " << (X == 0 || Y == 0)
        << " (X=" << X << ", Y=" << Y << ")" << endl;

    // г)
    X = -2; Y = -5; Z = -8;
    cout << "г) Каждое из чисел X, Y, Z отрицательное: " << (X < 0 && Y < 0 && Z < 0)
        << " (X=" << X << ", Y=" << Y << ", Z=" << Z << ")" << endl;

    // д)
    X = 10; Y = 15; Z = 21;
    bool только_одно_кратно_5 = (X % 5 == 0 && Y % 5 != 0 && Z % 5 != 0) ||
        (X % 5 != 0 && Y % 5 == 0 && Z % 5 != 0) ||
        (X % 5 != 0 && Y % 5 != 0 && Z % 5 == 0);
    cout << "д) Только одно из чисел X, Y, Z кратно пяти: " << только_одно_кратно_5
        << " (X=" << X << ", Y=" << Y << ", Z=" << Z << ")" << endl;

    // е)
    X = 50; Y = 120; Z = 80;
    cout << "е) Хотя бы одно из чисел X, Y, Z больше 100: " << (X > 100 || Y > 100 || Z > 100)
        << " (X=" << X << ", Y=" << Y << ", Z=" << Z << ")" << endl;

    return 0;
}