#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "RU");

    int x, y;

    cout << "Примеры логических выражений:" << endl;

    // Пример для a)
    x = 3; y = 4;
    cout << "a) x > 2 и y > 3 при x=" << x << ", y=" << y << ": " << (x > 2 && y > 3) << endl;

    // Пример для б)
    x = 0; y = -1;
    cout << "б) x > 1 или y > -2 при x=" << x << ", y=" << y << ": " << (x > 1 || y > -2) << endl;

    // Пример для в)
    x = 1; y = 3;
    cout << "в) x > 0 и y < 5 при x=" << x << ", y=" << y << ": " << (x > 0 && y < 5) << endl;

    // Пример для г)
    x = 4;
    cout << "г) x > 3 или x < -1 при x=" << x << ": " << (x > 3 || x < -1) << endl;

    // Пример для д)
    x = 5;
    cout << "д) x > 3 и x < 10 при x=" << x << ": " << (x > 3 && x < 10) << endl;

    // Пример для е)
    x = 1;
    cout << "е) неверно, что x > 2 при x=" << x << ": " << !(x > 2) << endl;

    // Пример для ж)
    x = 2;
    cout << "ж) неверно, что x > 0 и x < 5 при x=" << x << ": " << !(x > 0 && x < 5) << endl;

    // Пример для з)
    x = 15;
    cout << "з) 10 < x < 20 при x=" << x << ": " << (x > 10 && x < 20) << endl;

    // Пример для и)
    x = 3; y = 2;
    cout << "и) 0 < y < 4 и x < 5 при x=" << x << ", y=" << y << ": " << (y > 0 && y < 4 && x < 5) << endl;

    return 0;
}