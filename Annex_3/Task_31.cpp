#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "RU");

    int N;

    // a) Проверка: целое N кратно пяти или семи
    cout << "\na) N кратно пяти или семи:" << endl;

    N = 10;
    cout << "N = " << N << ": " << (N % 5 == 0 || N % 7 == 0)
        << " (10 кратно 5, но не 7)" << endl;

    N = 14;
    cout << "N = " << N << ": " << (N % 5 == 0 || N % 7 == 0)
        << " (14 кратно 7, но не 5)" << endl;

    N = 35;
    cout << "N = " << N << ": " << (N % 5 == 0 || N % 7 == 0)
        << " (35 кратно и 5, и 7)" << endl;

    N = 11;
    cout << "N = " << N << ": " << (N % 5 == 0 || N % 7 == 0)
        << " (11 не кратно ни 5, ни 7)" << endl;

    // б) Проверка: целое N кратно четырем и не оканчивается нулем
    cout << "\nб) N кратно четырем и не оканчивается нулем:" << endl;

    N = 12;
    cout << "N = " << N << ": " << (N % 4 == 0 && N % 10 != 0)
        << " (12 кратно 4, оканчивается на 2)" << endl;

    N = 20;
    cout << "N = " << N << ": " << (N % 4 == 0 && N % 10 != 0)
        << " (20 кратно 4, но оканчивается на 0)" << endl;

    N = 8;
    cout << "N = " << N << ": " << (N % 4 == 0 && N % 10 != 0)
        << " (8 кратно 4, оканчивается на 8)" << endl;

    N = 40;
    cout << "N = " << N << ": " << (N % 4 == 0 && N % 10 != 0)
        << " (40 кратно 4, но оканчивается на 0)" << endl;

    N = 9;
    cout << "N = " << N << ": " << (N % 4 == 0 && N % 10 != 0)
        << " (9 не кратно 4, оканчивается на 9)" << endl;

    // Демонстрация логического выражения
    cout << "\nЛогические выражения:" << endl;
    cout << "а) (N % 5 == 0) || (N % 7 == 0)" << endl;
    cout << "б) (N % 4 == 0) && (N % 10 != 0)" << endl;

    // Интерактивная проверка
    cout << "\nВведите число N для проверки: ";
    cin >> N;

    cout << "\nРезультаты для N = " << N << ":" << endl;
    cout << "а) Кратно 5 или 7: " << (N % 5 == 0 || N % 7 == 0) << endl;
    cout << "б) Кратно 4 и не оканчивается 0: " << (N % 4 == 0 && N % 10 != 0) << endl;

    return 0;
}