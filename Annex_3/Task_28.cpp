#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "RU");

    int A, B, C;

    cout << "Примеры условий:" << endl;

    // a)
    A = 120; B = 150;
    cout << "a) Каждое из чисел A и B больше 100: " << (A > 100 && B > 100)
        << " (A=" << A << ", B=" << B << ")" << endl;

    // б)
    A = 4; B = 7;
    bool только_одно_четное = (A % 2 == 0 && B % 2 != 0) || (A % 2 != 0 && B % 2 == 0);
    cout << "б) Только одно из чисел A и B четное: " << только_одно_четное
        << " (A=" << A << ", B=" << B << ")" << endl;

    // в)
    A = -5; B = 10;
    cout << "в) Хотя бы одно из чисел A и B положительно: " << (A > 0 || B > 0)
        << " (A=" << A << ", B=" << B << ")" << endl;

    // г)
    A = 9; B = 12; C = 15;
    cout << "г) Каждое из чисел A, B, C кратно трем: " << (A % 3 == 0 && B % 3 == 0 && C % 3 == 0)
        << " (A=" << A << ", B=" << B << ", C=" << C << ")" << endl;

    // д)
    A = 40; B = 60; C = 70;
    bool только_одно_меньше_50 = (A < 50 && B >= 50 && C >= 50) ||
        (A >= 50 && B < 50 && C >= 50) ||
        (A >= 50 && B >= 50 && C < 50);
    cout << "д) Только одно из чисел A, B, C меньше 50: " << только_одно_меньше_50
        << " (A=" << A << ", B=" << B << ", C=" << C << ")" << endl;

    // е)
    A = 5; B = -3; C = 10;
    cout << "е) Хотя бы одно из чисел A, B, C отрицательно: " << (A < 0 || B < 0 || C < 0)
        << " (A=" << A << ", B=" << B << ", C=" << C << ")" << endl;

    return 0;
}