#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "RU");

    cout << "Без операций деления, целочисленного деления и определения остатка" << endl;

    cout << "\nТрехзначные числа без повторяющихся цифр:" << endl;
    cout << "----------------------------------------" << endl;

    int count = 0;

    // Альтернативный способ без операций деления
    for (int a = 1; a <= 9; a++) {           // первая цифра (сотни)
        for (int b = 0; b <= 9; b++) {       // вторая цифра (десятки)
            for (int c = 0; c <= 9; c++) {   // третья цифра (единицы)
                // Проверяем, что все цифры разные
                if (a != b && a != c && b != c) {
                    int num = a * 100 + b * 10 + c;
                    cout << num << " ";
                    count++;

                    if (count % 10 == 0) {
                        cout << endl;
                    }
                }
            }
        }
    }

    cout << "\n\nВсего найдено: " << count << " чисел" << endl;

    return 0;
}