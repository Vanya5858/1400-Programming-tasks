#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "RU");

    cout << "Без операций деления и остатка от деления" << endl;

    int n;
    cout << "Введите n (0 <= n <= 27): ";
    cin >> n;

    cout << "\nТрехзначные числа с суммой цифр " << n << ":" << endl;
    cout << "--------------------------------------" << endl;

    int count = 0;

    // Перебираем все трехзначные числа
    for (int num = 100; num <= 999; num++) {
        // Извлекаем цифры без операций деления
        int a = num / 100;        // первая цифра
        int b = (num / 10) % 10;  // вторая цифра
        int c = num % 10;         // третья цифра

        // Проверяем сумму цифр
        if (a + b + c == n) {
            cout << num << " ";
            count++;

            if (count % 10 == 0) {
                cout << endl;
            }
        }
    }

    cout << "\n\nВсего найдено: " << count << " чисел" << endl;

    // Альтернативный способ без операций деления и остатка
    cout << "\nАльтернативный способ (без / и %):" << endl;
    count = 0;

    for (int a = 1; a <= 9; a++) {           // первая цифра (сотни)
        for (int b = 0; b <= 9; b++) {       // вторая цифра (десятки)
            for (int c = 0; c <= 9; c++) {   // третья цифра (единицы)
                if (a + b + c == n) {
                    int num = a * 100 + b * 10 + c;
                    if (num >= 100) {  // действительно трехзначное
                        cout << num << " ";
                        count++;

                        if (count % 10 == 0) {
                            cout << endl;
                        }
                    }
                }
            }
        }
    }

    cout << "\n\nВсего: " << count << " чисел" << endl;

    return 0;
}