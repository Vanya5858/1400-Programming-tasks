#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "RU");
    int a, b, c, d;
    cout << "Введите размеры стола (a b): ";
    cin >> a >> b;
    cout << "Введите размеры прямоугольников (c d): ";
    cin >> c >> d;

    // Размещение длинной стороной вдоль длинной стороны стола
    int count1 = (a / c) * (b / d);

    // Размещение длинной стороной вдоль короткой стороны стола
    int count2 = (a / d) * (b / c);

    cout << "При размещении длинной стороной вдоль длинной: " << count1 << " прямоугольников\n";
    cout << "При размещении длинной стороной вдоль короткой: " << count2 << " прямоугольников\n";

    if (count1 > count2) {
        cout << "Выгоднее размещать длинной стороной вдоль длинной стороны стола\n";
    }
    else if (count2 > count1) {
        cout << "Выгоднее размещать длинной стороной вдоль короткой стороны стола\n";
    }
    else {
        cout << "Оба способа дают одинаковое количество\n";
    }

    return 0;
}