def find_element_name():
    """Найти название химического элемента по его обозначению"""
    
    elements = {
        "водород": "H",
        "гелий": "He", 
        "литий": "Li",
        "бериллий": "Be",
        "бор": "B",
        "углерод": "C",
        "азот": "N",
        "кислород": "O",
        "фтор": "F",
        "неон": "Ne",
        "натрий": "Na",
        "магний": "Mg",
        "алюминий": "Al",
        "кремний": "Si",
        "фосфор": "P",
        "сера": "S",
        "хлор": "Cl",
        "аргон": "Ar",
        "калий": "K",
        "кальций": "Ca",
        "медь": "Cu",
        "цинк": "Zn",
        "серебро": "Ag",
        "золото": "Au"
    }
    
    symbol = input("Введите обозначение химического элемента: ")
    
    # Поиск элемента по значению
    found = False
    for name, sym in elements.items():
        if sym == symbol:
            print(f"Элемент с обозначением {symbol}: {name}")
            found = True
            break
    
    if not found:
        print(f"Элемент с обозначением '{symbol}' не найден")

# Запуск программы
if __name__ == "__main__":
    find_element_name()
