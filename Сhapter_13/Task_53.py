def find_element_symbol():
    """Найти обозначение химического элемента по его названию"""
    
    elements = {
        "водород": "H",
        "гелий": "He", 
        "литий": "Li",
        "бериллий": "Be",
        "бор": "B",
        "углерод": "C",
        "азот": "N",
        "кислород": "O",
        "фтор": "F",
        "неон": "Ne",
        "натрий": "Na",
        "магний": "Mg",
        "алюминий": "Al",
        "кремний": "Si",
        "фосфор": "P",
        "сера": "S",
        "хлор": "Cl",
        "аргон": "Ar",
        "калий": "K",
        "кальций": "Ca",
        "медь": "Cu",
        "цинк": "Zn",
        "серебро": "Ag",
        "золото": "Au"
    }
    
    element_name = input("Введите название химического элемента: ").lower()
    
    if element_name in elements:
        print(f"Обозначение элемента {element_name}: {elements[element_name]}")
    else:
        print(f"Элемент '{element_name}' не найден в словаре")

# Запуск программы
if __name__ == "__main__":
    find_element_symbol()
