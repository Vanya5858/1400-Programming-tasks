#include <iostream>
#include <string>
using namespace std;

struct Student {
    string surname;
    int marks[10]; // оценки по 10 предметам
};

int sumMarks(Student student) {
    int sum = 0;
    for (int i = 0; i < 10; i++) {
        sum += student.marks[i];
    }
    return sum;
}

void findStudents(Student students[], int n) {
    int maxSum = -1, minSum = 101; // максимально возможная сумма 10*5=50, минимальная 10*1=10
    string maxStudent, minStudent;

    for (int i = 0; i < n; i++) {
        int sum = sumMarks(students[i]);

        if (sum > maxSum) {
            maxSum = sum;
            maxStudent = students[i].surname;
        }

        if (sum < minSum) {
            minSum = sum;
            minStudent = students[i].surname;
        }
    }

    cout << "а) Ученик с наибольшей суммой оценок: " << maxStudent
        << " (сумма: " << maxSum << ")" << endl;
    cout << "б) Ученик с наименьшей суммой оценок: " << minStudent
        << " (сумма: " << minSum << ")" << endl;
}

