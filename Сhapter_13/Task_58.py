def school_classes_dictionary():
    """Словарь с количеством учащихся в классах"""
    
    classes = {
        "1а": 24,
        "1б": 26,
        "2а": 28,
        "2б": 25,
        "3а": 30,
        "3б": 27,
        "4а": 29,
        "4б": 26,
        "5а": 32,
        "5б": 30,
        "6а": 31,
        "6б": 29,
        "7а": 33,
        "7б": 30,
        "8а": 34,
        "8б": 31,
        "9а": 35,
        "9б": 32,
        "10а": 36,
        "10б": 33,
        "11а": 37,
        "11б": 34
    }
    
    class_name = input("Введите название класса (например, 5а): ").strip()
    
    if class_name in classes:
        print(f"В классе {class_name} учится {classes[class_name]} учеников")
    else:
        print(f"Класс '{class_name}' не найден")

# Запуск программы
if __name__ == "__main__":
    school_classes_dictionary()
