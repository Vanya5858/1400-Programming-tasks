def school_management_system():
    """Система управления данными школы"""
    
    # Исходный словарь классов
    classes = {
        "1а": 24,
        "1б": 26,
        "2а": 28,
        "2б": 25,
        "3а": 30,
        "3б": 27,
        "4а": 29,
        "4б": 26,
        "5а": 32,
        "5б": 30,
        "6а": 31,
        "6б": 29
    }
    
    print("Исходный состав школы:")
    print("======================")
    total_students = 0
    for class_name, count in classes.items():
        print(f"{class_name}: {count} чел.")
        total_students += count
    print(f"Всего учащихся: {total_students} чел.")
    
    # 1. В трех классах изменилось количество учащихся
    print("\n1. В трех классах изменилось количество учащихся:")
    classes["2а"] = 30  # было 28
    classes["4б"] = 28  # было 26
    classes["6а"] = 33  # было 31
    print("   - В классе 2а теперь 30 учеников (было 28)")
    print("   - В классе 4б теперь 28 учеников (было 26)")
    print("   - В классе 6а теперь 33 ученика (было 31)")
    
    # 2. В школе появились два новых класса
    print("\n2. В школе появились два новых класса:")
    classes["7а"] = 34
    classes["7б"] = 32
    print("   - Добавлен класс 7а с 34 учениками")
    print("   - Добавлен класс 7б с 32 учениками")
    
    # 3. В школе расформировали один из классов
    print("\n3. В школе расформировали один из классов:")
    removed_count = classes.pop("3б", 0)
    print(f"   - Расформирован класс 3б (в нем было {removed_count} учеников)")
    
    # После внесения изменений:
    print("\nПосле внесения изменений:")
    print("========================")
    
    # 1) Определить общее количество учащихся
    total_students = sum(classes.values())
    print(f"1) Общее количество учащихся: {total_students} чел.")
    
    # 2) Вывести содержимое словаря
    print("\n2) Содержимое словаря (в произвольном порядке классов):")
    print("   Класс | Количество")
    print("   ------------------")
    for class_name, count in classes.items():
        print(f"   {class_name} | {count}")
    
    # Дополнительно: сортировка по названию класса
    print("\nДополнительно: отсортированный список:")
    for class_name in sorted(classes.keys()):
        print(f"   {class_name}: {classes[class_name]} учеников")

# Запуск программы
if __name__ == "__main__":
    school_management_system()
