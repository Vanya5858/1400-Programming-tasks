void findBirthdayToday(StudentBirth students[], int n, int todayMonth, int todayDay) {
    bool found = false;

    for (int i = 0; i < n; i++) {
        if (students[i].birthMonth == todayMonth && students[i].birthDay == todayDay) {
            cout << students[i].name << " " << students[i].surname << endl;
            found = true;
        }
    }

    if (!found) {
        cout << "Сегодня никто не празднует день рождения" << endl;
    }
}

