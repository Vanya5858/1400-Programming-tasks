#include <iostream>
#include <string>
using namespace std;

struct Student {
    string surname;
    string name;
    string address;
    int school;
    int grade;
};

void filterSeniorStudents(Student students[], int n, Student seniors[], int& count) {
    count = 0;
    for (int i = 0; i < n; i++) {
        if (students[i].grade >= 10 && students[i].grade <= 11) {
            seniors[count] = students[i];
            count++;
        }
    }
}

void printStudents(Student students[], int n) {
    for (int i = 0; i < n; i++) {
        cout << students[i].surname << " " << students[i].name
            << ", адрес: " << students[i].address
            << ", школа: " << students[i].school
            << ", класс: " << students[i].grade << endl;
    }
}

