def check_symbol_exists():
    """Проверить наличие обозначения химического элемента в словаре"""
    
    elements = {
        "водород": "H",
        "гелий": "He", 
        "литий": "Li",
        "бериллий": "Be",
        "бор": "B",
        "углерод": "C",
        "азот": "N",
        "кислород": "O",
        "фтор": "F",
        "неон": "Ne",
        "натрий": "Na",
        "магний": "Mg",
        "алюминий": "Al",
        "кремний": "Si",
        "фосфор": "P",
        "сера": "S",
        "хлор": "Cl",
        "аргон": "Ar",
        "калий": "K",
        "кальций": "Ca",
        "медь": "Cu",
        "цинк": "Zn",
        "серебро": "Ag",
        "золото": "Au"
    }
    
    symbol = input("Введите обозначение химического элемента: ")
    
    # Вариант 1: с использованием метода values()
    print("Вариант 1 (с использованием values()):")
    if symbol in elements.values():
        print(f"Обозначение '{symbol}' присутствует в словаре")
    else:
        print(f"Обозначение '{symbol}' отсутствует в словаре")
    
    # Вариант 2: без использования values()
    print("\nВариант 2 (без values()):")
    found = False
    for name, sym in elements.items():
        if sym == symbol:
            found = True
            break
    
    if found:
        print(f"Обозначение '{symbol}' присутствует в словаре")
    else:
        print(f"Обозначение '{symbol}' отсутствует в словаре")

# Запуск программы
if __name__ == "__main__":
    check_symbol_exists()
