#include <string>
using namespace std;

struct Employee {
    string surname;
    string name;
    string patronymic;
    string address;
    int hireMonth;
    int hireYear;
};

void printEmployeesWorked3Years(Employee employees[], int n, int currentYear = 2024, int currentMonth = 12) {
    for (int i = 0; i < n; i++) {
        int yearsWorked = currentYear - employees[i].hireYear;

        if (currentMonth < employees[i].hireMonth) {
            yearsWorked--;
        }

        if (yearsWorked >= 3) {
            cout << employees[i].surname << " "
                << employees[i].name << " "
                << employees[i].patronymic << " - "
                << employees[i].address << endl;
        }
    }
}

